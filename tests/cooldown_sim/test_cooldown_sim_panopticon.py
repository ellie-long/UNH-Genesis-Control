"""The Panopticon overview screen (gui/genesis_panopticon.bob).

The screen is generated by tools/make_panopticon.py.  Every PV on it must be
served by a Genesis IOC, instruments Genesis does not read yet must be grey
"not in Genesis yet" placeholders without a PV, and the insert drawing must
keep the thermometers in their physical order, coloured like their traces.
"""

import importlib
import importlib.util
import re
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

from cooldown_sim import phoebus, pvlist
from cooldown_sim.testing import softioc_stub

ROOT = Path(__file__).resolve().parents[2]
BOB = ROOT / "gui" / "genesis_panopticon.bob"

#: Genesis IOC profiles whose records the screen may show
CONFIG_DIRS = ("configs/target_physical", "configs/commissioning/microwave_physical",
               "configs/commissioning/ssrf_sim_active", "configs/ssrf_physical")

#: instruments the DAQ shows and Genesis does not read yet
PLACEHOLDERS = (
    "MagnetLevelTrend", "MagnetLevelBar", "MagnetLevel", "MagnetLevelScale",
    "FlowTrend", "FridgeLevelTrend", "FridgeLevel", "VaporTemp", "ManometerLo", "Pirani",
    "SeparatorFlow", "RootsTotalFlow", "BackingLFlow", "BackingRFlow",
    "LabTrend", "BackingPumpL", "BackingPumpR", "VMETemp", "SeparatorHeater",
    "TargetStick", "MagnetCurrent", "MagnetField", "NMRFreqFromField", "SwitchHeater",
    "SIG", "Magic", "EPRSignal", "EPRLockIn", "EPRCoils", "EPRFieldSweep", "SlowSweep",
)

#: top to bottom: the physical order of the sensors in the insert
FRIDGE_ORDER = ("F1", "F2", "F3", "F4", "F5", "F6", "F8", "F7", "F9", "F10", "F11", "T1", "T3")
MAGNET_ORDER = ("M1", "M2", "M3", "M4", "M5")


def _generator():
    spec = importlib.util.spec_from_file_location("make_panopticon", ROOT / "tools" / "make_panopticon.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _fitter_records():
    with softioc_stub.installed() as stub:
        mod = importlib.import_module("online_fitter.epics_run")
        iface = mod.FitterEpicsInterface.__new__(mod.FitterEpicsInterface)
        iface.pvs = {}
        iface._create_pvs()
        return {f"{mod.DEFAULT_PREFIX}:{name}" for name in stub.builder.records}


def served_pvs() -> set[str]:
    """PV names some Genesis IOC serves: its profile's records, the standard
    instrument health PVs, the logic IOCs' records (cooldown_sim.pvlist, built
    from the IOC code) and the online fitter's records (built by its code)."""
    # the _Conn PVs the archiver lists are not served (known issue conn-pv-not-served)
    served = {pv for pv in pvlist.archiver_explicit_pvs(ROOT) if not pv.endswith("_Conn")}
    for folder in CONFIG_DIRS:
        for path in sorted((ROOT / folder).glob("*/settings.yaml")):
            cfg = yaml.safe_load(path.read_text(encoding="utf-8"))
            prefix = (cfg.get("general") or {}).get("prefix")
            for key, section in cfg.items():
                if key == "general" or not isinstance(section, dict):
                    continue
                rp = section.get("record_prefix") or ""
                served.update(f"{prefix}:{rp}{rec}" for rec in section.get("records") or {})
                if str(section.get("module", "")).startswith(("target_ioc.instruments", "microwave_ioc")):
                    served.update(f"{prefix}:{h}" for h in pvlist.HEALTH)
    for table in (pvlist.CRYO_LOGIC, pvlist.MW_PVS, pvlist.SSRF_PVS):
        for prefix, names in table.items():
            served.update(f"{prefix}:{n}" for n in names)
    served.update(f"UNH:GEN:SSRF:SEQ:{n}" for n in pvlist.SSRF_SEQ_PVS)
    served |= _fitter_records()
    return served


def _widgets():
    return ET.parse(BOB).getroot().findall("widget")


def _by_name():
    return {w.findtext("name"): w for w in _widgets()}


def test_committed_screen_is_current():
    assert BOB.read_text(encoding="utf-8") == _generator().build(), \
        "regenerate: python tools/make_panopticon.py"


def test_screen_pvs_exist_and_links_resolve():
    text = BOB.read_text(encoding="utf-8")
    pvs = set(re.findall(r"ca://([A-Za-z0-9:_]+)", text))
    assert len(pvs) > 60
    missing = pvs - served_pvs()
    assert not missing, sorted(missing)
    # Channel Access only, never a sim or local PV
    names = re.findall(r"<(?:pv_name|x_pv|y_pv)>([^<]*)<", text)
    assert names and all(n.startswith("ca://UNH:GEN:") for n in names), \
        [n for n in names if not n.startswith("ca://UNH:GEN:")]
    assert "UNH:GEN:SIM" not in text and "SIMULATION" not in text
    root = ET.parse(BOB).getroot()
    files = [f.text for f in root.iter("file")]
    assert files
    for f in files:
        assert (BOB.parent / f).exists(), f


def test_screen_is_read_only():
    root = ET.parse(BOB).getroot()
    inputs = {"textentry", "combo", "spinner", "slider", "scaledslider", "slide_button", "bool_button",
              "choice_button", "radio", "checkbox", "thumbwheel", "scrollbar"}
    assert not [w.findtext("name") for w in root.iter("widget") if w.get("type") in inputs]
    actions = [a.get("type") for a in root.iter("action")]
    assert actions and set(actions) == {"open_display"}
    assert {a.findtext("target") for a in root.iter("action")} == {"tab"}


def test_placeholders_are_grey_and_have_no_pv():
    gen = _generator()
    widgets = _by_name()
    found = {n.removeprefix("Placeholder_") for n in widgets if n.startswith("Placeholder_")}
    assert set(PLACEHOLDERS) <= found, sorted(set(PLACEHOLDERS) - found)
    grey = gen.col(gen.GREY_FILL)
    for name in found:
        w = widgets[f"Placeholder_{name}"]
        assert w.find("pv_name") is None, name
        if w.get("type") == "label":
            assert gen.NOT_YET in w.findtext("text") or name == "Magic", name
            assert gen.col(gen.GREY_TEXT) in ET.tostring(w, encoding="unicode").replace(" />", "/>"), name
        if w.get("type") == "rectangle":
            assert grey in ET.tostring(w, encoding="unicode").replace(" />", "/>"), name
    # every placeholder trend says so
    text = BOB.read_text(encoding="utf-8")
    assert text.count(f"<text>{gen.NOT_YET}</text>") >= 25


def _trace_colours():
    colours = {}
    for w in _widgets():
        if w.get("type") != "stripchart":
            continue
        for trace in w.iter("trace"):
            c = trace.find("color/color")
            colours[trace.findtext("y_pv")] = (int(c.get("red")), int(c.get("green")), int(c.get("blue")))
    return colours


def test_insert_readouts_follow_the_sensor_order_and_trace_colours():
    widgets = _by_name()
    traces = _trace_colours()

    def top(sensor):
        return int(widgets[f"Insert_{sensor}"].findtext("y"))

    for order in (FRIDGE_ORDER, MAGNET_ORDER):
        ys = [top(s) for s in order]
        assert ys == sorted(ys) and len(set(ys)) == len(ys), dict(zip(order, ys))
    # F8 sits above F7; the target cup is below the bottom of the fridge
    assert top("F8") < top("F7") and top("F11") < top("T1") < top("T3")
    for sensor in FRIDGE_ORDER + MAGNET_ORDER:
        w = widgets[f"Insert_{sensor}"]
        pv = w.findtext("pv_name")
        assert pv.endswith(f":{sensor}_TI"), pv
        bg = w.find("background_color/color")
        assert traces[pv] == (int(bg.get("red")), int(bg.get("green")), int(bg.get("blue"))), sensor


def test_trends_have_the_daq_windows_and_log_pressures():
    charts = {w.findtext("name"): w for w in _widgets() if w.get("type") == "stripchart"}
    assert charts["Trend_ShellsVacuum"].findtext("start") == "2 days"
    assert charts["Trend_Polarization"].findtext("start") == "3 hours"
    for name in ("Trend_ShellsVacuum", "Trend_FridgePressures"):
        assert {a.findtext("log_scale") for a in charts[name].iter("y_axis")} == {"true"}, name
    for w in charts.values():
        assert w.get("version") == "2.1.0"          # 'start' is the 2.1.0 time-range property
        assert w.findtext("start")


def test_polarization_headline_is_the_area_method():
    # the DAQ's "Polarization" readout is the area method
    assert _by_name()["NMR_P"].findtext("pv_name") == "ca://UNH:GEN:SSRF:FIT:P_AREA"


def test_screen_opens_from_the_simulator():
    assert phoebus.LIVE_SCREENS["panopticon"] == BOB.name
    assert (ROOT / "gui" / phoebus.LIVE_SCREENS["panopticon"]).exists()
