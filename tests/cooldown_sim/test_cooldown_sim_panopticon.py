def _trace_colours():
    colours = {}
    for w in _widgets():
        if w.get("type") != "stripchart":
            continue
        for trace in w.iter("trace"):
            c = trace.find("color/color")
            colours[trace.findtext("y_pv")] = (int(c.get("red")), int(c.get("green")), int(c.get("blue")))
    return colours


def _rgb(node):
    return int(node.get("red")), int(node.get("green")), int(node.get("blue"))


def test_insert_follows_the_sensor_positions_and_trace_colours():
    widgets = _by_name()
    traces = _trace_colours()

    def centre_y(name):
        w = widgets[name]
        return int(w.findtext("y")) + int(w.findtext("height")) / 2

    for kind in ("Marker", "Insert"):           # markers on the drawing, and their readout boxes
        for order in (FRIDGE_ORDER, MAGNET_ORDER):
            ys = [centre_y(f"{kind}_{s}") for s in order]
            assert ys == sorted(ys) and len(set(ys)) == len(ys), (kind, dict(zip(order, ys)))
        # F8 sits above F7; the target cup is below the bottom of the fridge
        assert centre_y(f"{kind}_F8") < centre_y(f"{kind}_F7")
        assert centre_y(f"{kind}_F11") < centre_y(f"{kind}_T1") < centre_y(f"{kind}_T3")

    def centre_x(name):
        w = widgets[name]
        return int(w.findtext("x")) + int(w.findtext("width")) / 2

    def box(name):
        w = widgets[name]
        x, y = int(w.findtext("x")), int(w.findtext("y"))
        return x, y, x + int(w.findtext("width")), y + int(w.findtext("height"))

    # F1 inside the upper insert, about halfway from its wall to the pumping tube
    ins, tube, f1 = box("Shape_Upper_Insert"), box("Shape_Pumping_Tube"), box("Marker_F1")
    assert ins[1] < f1[1] and f1[3] < ins[3] and tube[2] < f1[0] and f1[2] < ins[2]
    assert abs(centre_x("Marker_F1") - (tube[2] + ins[2]) / 2) <= 5
    assert centre_x("Marker_F3") < centre_x("Marker_F4") and centre_x("Marker_F7") < centre_x("Marker_F8")
    # F3 hangs from the bottom of the lowest upper plate
    lowest_upper = max((box(n) for n in widgets if re.fullmatch(r"Baffle_U\d+", n)), key=lambda b: b[1])
    assert box("Marker_F3")[1] == lowest_upper[3]
    # F5 sits on the separator's top, F6 hangs from its bottom; T1 and T3 in the target cup
    sep, cup = widgets["Shape_Separator"], widgets["Target_Cup"]
    sep_top, sep_bottom = int(sep.findtext("y")), int(sep.findtext("y")) + int(sep.findtext("height"))
    assert box("Marker_F5")[3] == sep_top and box("Marker_F6")[1] == sep_bottom
    can = widgets["Shape_Fridge_Can"]
    assert int(sep.findtext("width")) > int(can.findtext("width"))     # the can is wider than the column
    for s in ("T1", "T3"):
        assert int(cup.findtext("y")) <= centre_y(f"Marker_{s}") <= int(cup.findtext("y")) + int(cup.findtext("height"))
    for sensor in FRIDGE_ORDER + MAGNET_ORDER:
        w = widgets[f"Insert_{sensor}"]
        pv = w.findtext("pv_name")
        assert pv.endswith(f":{sensor}_TI"), pv
        colour = traces[pv]
        assert colour == _rgb(w.find("background_color/color")), sensor
        assert colour == _rgb(widgets[f"Marker_{sensor}"].find("background_color/color")), sensor
    # the long-removed shell sensors S1-S3 are not drawn at all
    assert not [n for n in widgets if n.startswith("Removed_") or n.startswith("Marker_S")]


def test_heat_exchanger_is_two_stacks_around_the_separator():
    widgets = _by_name()

    def plates(stack):
        ys = sorted(int(w.findtext("y")) for n, w in widgets.items() if re.fullmatch(rf"Baffle_{stack}\d+", n))
        return ys, [b - a for a, b in zip(ys, ys[1:])]

    upper, upper_pitch = plates("U")
    lower, lower_pitch = plates("L")
    # as built: 5 upper plates on 1.94" spacers, 10 lower plates on 0.75" spacers
    assert len(upper) == 5 and len(lower) == 10
    for pitch in (upper_pitch, lower_pitch):                                  # each stack evenly spaced
        assert max(pitch) - min(pitch) <= 1, pitch
    assert 2.0 <= upper_pitch[0] / lower_pitch[0] <= 3.2                      # 1.94 / 0.75 = 2.6
    assert len([n for n in widgets if n.startswith("Baffle_")]) == 15         # no other plates

    def edge(name, key):
        w = widgets[name]
        return int(w.findtext("y")) + (int(w.findtext("height")) if key == "bottom" else 0)

    def y(sensor):
        w = widgets[f"Marker_{sensor}"]
        return int(w.findtext("y")) + int(w.findtext("height")) / 2

    # the separator sits in the gap: no plate between the stacks
    assert upper[-1] < edge("Shape_Separator", "top") and edge("Shape_Separator", "bottom") < lower[0]
    assert upper[-1] < y("F3") < y("F4") < y("F5") and y("F6") < y("F8") < y("F7")
    assert upper[0] > y("F2")                                                 # F2 above the upper stack
    assert abs(y("F8") - lower[0]) <= 2 * lower_pitch[0]                       # F8/F7 at the top of the lower stack
    assert lower[-1] < y("F11") < edge("Shape_Nose", "top")                    # F11 just below it, no plates in the nose


def test_magnet_space_baffles_solenoid_and_sensors():
    gen = _generator()
    widgets = _by_name()

    def box(name):
        w = widgets[name]
        x, y = int(w.findtext("x")), int(w.findtext("y"))
        return x, y, x + int(w.findtext("width")), y + int(w.findtext("height"))

    def inches(y):
        return gen.level_inches(y)

    # the solenoid: the nose fits in its bore; its top just under the 16.5" support baffle
    coil_l, coil_r, nose = box("Coil_L"), box("Coil_R"), box("Shape_Nose")
    assert coil_l[2] <= nose[0] and nose[2] <= coil_r[0]
    top_in, bottom_in = inches(coil_r[1]), inches(coil_r[3])
    assert 15.5 <= top_in < 16.5 and bottom_in < 2
    support = box("Magnet_Baffle_Support")
    # the support baffle is as wide as the neck baffles
    assert abs((support[2] - support[0]) - (box("Magnet_Baffle_N1")[2] - box("Magnet_Baffle_N1")[0])) <= 1
    # the dewar's outer wall encloses the whole LHe space
    outer, space = box("Magnet_Dewar_Outer"), box("Magnet_LHe_Space")
    assert outer[0] < space[0] and outer[2] > space[2] and outer[1] <= space[1] and outer[3] > space[3]
    assert abs(inches(support[3]) - 16.5) <= 0.5 and support[3] <= coil_r[1]
    # 5 neck baffles above the belly, spacing growing upward
    neck = sorted((box(n)[1] for n in widgets if re.fullmatch(r"Magnet_Baffle_N\d", n)), reverse=True)
    assert len(neck) == 5
    gaps = [a - b for a, b in zip(neck, neck[1:])]
    assert all(g2 > g1 for g1, g2 in zip(gaps, gaps[1:])), gaps
    # the belly is wider than the bore and the neck
    pts = [(float(p.get("x")), float(p.get("y"))) for p in widgets["Magnet_LHe_Space"].iter("point")]
    xs = sorted({x for x, _ in pts})
    assert len(xs) == 6                       # bore, belly and neck walls on each side
    assert xs[-1] - xs[0] > xs[-2] - xs[1] and xs[-1] - xs[0] > xs[-3] - xs[2]

    # sensors sit on what the lab says they sit on
    def marker(s):
        return box(f"Marker_{s}")

    assert marker("M2")[3] == box("Magnet_Baffle_N1_L")[1]        # on the lowest neck baffle
    assert marker("M3")[3] == box("Magnet_Baffle_Support_L")[1]   # on the support baffle
    assert abs(inches((marker("M4")[1] + marker("M4")[3]) / 2) - top_in) <= 0.5      # solenoid top
    assert abs(inches((marker("M5")[1] + marker("M5")[3]) / 2) - bottom_in) <= 0.5   # solenoid bottom
    assert marker("M1")[3] < marker("M2")[1]                      # M1 higher, in the neck
    for s in ("M1", "M2", "M3", "M4", "M5"):                      # left side, outside the solenoid
        assert marker(s)[2] <= coil_l[0], s


