#!/usr/bin/env python3
"""Generate gui/genesis_pumping_cart.bob: the pumping cart's IONIVAC.

Run:  python tools/make_pumping_cart.py

The lab has two IONIVACs: the shells' (the insulating vacuum, on the
Panopticon) and this one, on the portable pumping station, a cart with
roughing and turbo pumps that is moved around the lab (Genesis IOC
`ionivac_pump`, `UNH:GEN:CRYO:ION:PUMP`, TXI040 port 2, TCP 5005). Ells
(2026-10-22): record it, give it its own screen with a plot, and keep it OFF
the Panopticon, so it is never mistaken for the shells' vacuum.

Read-only, like the Panopticon. The trend is the trend-history IOC's CART
group (logic_devices/trend_history.py), full the moment the screen opens.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "gui" / "genesis_pumping_cart.bob"
W, H = 900, 560

_spec = importlib.util.spec_from_file_location("make_panopticon", Path(__file__).with_name("make_panopticon.py"))
pan = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pan)

CART = "UNH:GEN:CRYO:ION:PUMP"
CART_COLOUR = (0, 120, 140)


def build() -> str:
    pan._n[0] = 0
    w = [pan.rect(0, 0, W, H, pan.WHITE, name="Page"),
         pan.rect(0, 0, W, 44, pan.NAVY_DARK, name="Header"),
         pan.label("UNH Genesis - Pumping Cart", 14, 2, 420, 26, 18, True, pan.WHITE, name="Title"),
         pan.label("Portable pumping station's IONIVAC (read-only). Not the shells' vacuum.",
                   15, 26, 520, 16, 9, False, pan.WHITE),
         pan.open_button("Panopticon", "genesis_panopticon.bob", W - 124, 8, 110, 28)]
    w.append(pan.card("Pumping cart IONIVAC", 4, 48, W - 8, H - 52, "Cart"))
    w.append(pan.history_plot("CartPressure", "Pumping cart pressure (Torr, log)", 12, 80, 640, 470, "CART",
                              [("Cart IONIVAC", "Ion_PI", CART_COLOUR, 0)],
                              [("Torr", True, 1e-9, 1e3)], 360))
    x = 664
    w.append(pan.field("Pressure", f"{CART}:Ion_PI", x, 80, 224, 14, prec=2, fmt=2))
    w.append(pan.field("Raw count", f"{CART}:Ion_Raw", x, 130, 224, 11, units=False, bold=False))
    w.append(pan.field("Gauge comm", f"{CART}:COMM", x, 176, 224, 11, bold=False))
    w.append(pan.field("Last good read", f"{CART}:LAST_OK", x, 222, 224, 10, bold=False))
    w.append(pan.field("Error", f"{CART}:ERROR", x, 268, 224, 10, bold=False))
    w.append(pan.label("The cart is moved around the lab and pumps on whatever it is connected to. "
                       "Its alarm limits are its own; the shells' vacuum is the IONIVAC on the "
                       "Panopticon (Shells Space).", x, 330, 224, 120, 9, False, pan.MUTED, wrap=True,
                       valign=0))
    body = "\n  ".join(w)
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
            f"<!-- Generated by tools/make_pumping_cart.py: edit the generator, not this file. -->\n"
            f'<display version="2.0.0">\n'
            f"  <name>Genesis Pumping Cart</name>\n  <width>{W}</width>\n  <height>{H}</height>\n"
            f"  <background_color>{pan.col(pan.WHITE)}</background_color>\n  {body}\n</display>\n")


def main():
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
